/// TAS5830 power state
#[derive(Debug, Clone, Copy, PartialEq, Eq, defmt::Format)]
pub enum PowerState {
    DeepSleep,
    Sleep,
    HiZ,
    Play,
    Unknown(u8),
}

impl From<u8> for PowerState {
    fn from(val: u8) -> Self {
        match val & 0x03 {
            0 => PowerState::DeepSleep,
            1 => PowerState::Sleep,
            2 => PowerState::HiZ,
            3 => PowerState::Play,
            _ => PowerState::Unknown(val),
        }
    }
}

/// TAS5830 driver error
#[derive(Debug, defmt::Format)]
pub enum Error<E> {
    /// I2C communication error
    I2c(E),
}

impl<E> From<E> for Error<E> {
    fn from(e: E) -> Self {
        Error::I2c(e)
    }
}

/// TAS5830 amplifier driver
pub struct Tas5830<'a, I> {
    i2c: I,
    address: u8,
    volume: u8,
    muted: bool,
    pdn: Output<'a>,
    mute_pin: Output<'a>,
}

impl<'a, I, E> Tas5830<'a, I>
where
    I: I2c<Error = E>,
{
    /// Create a new TAS5830 driver with control pins.
    ///
    /// Both pins start low (power-down asserted, muted).
    pub fn new(i2c: I, address: u8, pdn: Output<'a>, mute_pin: Output<'a>) -> Self {
        Self {
            i2c,
            address,
            volume: 0x30, // Default -24dB (matches config.h)
            muted: false,
            pdn,
            mute_pin,
        }
    }

    /// Create with default address (0x60)
    pub fn new_default(i2c: I, pdn: Output<'a>, mute_pin: Output<'a>) -> Self {
        Self::new(i2c, DEFAULT_ADDRESS, pdn, mute_pin)
    }

    /// Phase 1: PDN high + reset into Hi-Z.
    ///
    /// Call this BEFORE I2S clocks are started.
    /// Matches the C reference: `gpio_pdn_set_value(1)` + `transmit_registers(init_sequence1)`.
    pub async fn init(&mut self) -> Result<(), Error<E>> {
        // Pull PDN high, keep muted
        self.pdn.set_high();
        self.mute_pin.set_low();
        embassy_time::Timer::after(embassy_time::Duration::from_millis(5)).await;

        // Read device ID to verify communication
        let die_id = self.read_reg(reg::DIE_ID).await?;
        defmt::info!("TAS5830 DIE_ID: {:#04x}", die_id);

        // Transmit init sequence 1 (reset + Hi-Z)
        self.transmit_registers(INIT_SEQUENCE_1).await?;

        defmt::info!("TAS5830 init phase 1 complete (Hi-Z, waiting for I2S clocks)");
        Ok(())
    }

    /// Phase 2: Load DSP coefficients + enter Play + unmute.
    ///
    /// Call this AFTER I2S clocks (BCLK/WCLK) are running.
    /// Matches the C reference: 5ms delay + `transmit_registers(init_sequence2)`.
    pub async fn play(&mut self) -> Result<(), Error<E>> {
        // 5ms delay for uCDSP to boot (per C reference)
        embassy_time::Timer::after(embassy_time::Duration::from_millis(5)).await;

        // Transmit init sequence 2 (DSP config + coefficients + enter Play)
        self.transmit_registers(INIT_SEQUENCE_2).await?;

        // Verify power state
        let state = self.get_power_state().await?;
        defmt::info!("TAS5830 power state: {:?}", state);
        if state != PowerState::Play {
            defmt::warn!("TAS5830 not in PLAY mode: {:?}", state);
        }

        // Unmute hardware pin
        self.mute_pin.set_high();
        defmt::info!("TAS5830 playing, unmuted");
        Ok(())
    }

    /// Transmit a sequence of (register, value) pairs over I2C
    async fn transmit_registers(&mut self, regs: &[(u8, u8)]) -> Result<(), Error<E>> {
        for &(reg, val) in regs {
            self.write_reg(reg, val).await?;
        }
        Ok(())
    }

    /// Set the digital volume (register 0x4C)
    ///
    /// Volume is in 0.5dB steps: 0x00 = 0dB, 0xFF = -127.5dB
    pub async fn set_volume(&mut self, volume: u8) -> Result<(), Error<E>> {
        self.volume = volume;
        if !self.muted {
            self.write_reg(reg::DIG_VOL, volume).await?;
        }
        defmt::debug!(
            "TAS5830 volume: {:#04x} ({} dB)",
            volume,
            -(volume as i16) / 2
        );
        Ok(())
    }

    pub async fn set_volume_percent(&mut self, percent: u8) -> Result<(), Error<E>> {
        const VOL_START: f32 = 0.5;
        const VOL_SCALE: f32 = 30.0;
        const VOL_RANGE: f32 = VOL_START + VOL_SCALE;
        let vol_scaled = ((percent as f32) / 100.0 * VOL_SCALE).clamp(0.001, VOL_SCALE) + VOL_START;
        let percent_scaled = (vol_scaled.log2() / VOL_RANGE.log2() * 100.0).clamp(0.0, 100.0) as u8;
        defmt::info!(
            "TAS5830 set volume percent: {} scaled: {}",
            percent,
            percent_scaled
        );
        // Map 0-100% to 0xCF-0x00 (mute to 0dB)
        let volume = if percent_scaled >= 100 {
            0x00
        } else {
            0xCF - ((percent_scaled as u16 * 0xCF) / 100) as u8
        };
        self.set_volume(volume).await
    }

    /// Get volume as percentage
    pub fn get_volume_percent(&self) -> u8 {
        if self.volume >= 0xCF {
            0
        } else {
            (((0xCF - self.volume) as u16 * 100) / 0xCF) as u8
        }
    }

    /// Mute the amplifier (digital mute via volume register)
    pub async fn mute(&mut self) -> Result<(), Error<E>> {
        self.muted = true;
        self.write_reg(reg::DIG_VOL, 0xFF).await?;
        defmt::debug!("TAS5830 muted");
        Ok(())
    }

    /// Unmute the amplifier
    pub async fn unmute(&mut self) -> Result<(), Error<E>> {
        self.muted = false;
        self.write_reg(reg::DIG_VOL, self.volume).await?;
        defmt::debug!("TAS5830 unmuted");
        Ok(())
    }

    /// Check if muted
    pub fn is_muted(&self) -> bool {
        self.muted
    }

    /// Toggle mute state
    pub async fn toggle_mute(&mut self) -> Result<bool, Error<E>> {
        if self.muted {
            self.unmute().await?;
        } else {
            self.mute().await?;
        }
        Ok(self.muted)
    }

    /// Get power state
    pub async fn get_power_state(&mut self) -> Result<PowerState, Error<E>> {
        let state = self.read_reg(reg::POWER_STATE).await?;
        Ok(PowerState::from(state))
    }

    /// Write a single register
    async fn write_reg(&mut self, reg: u8, value: u8) -> Result<(), Error<E>> {
        self.i2c.write(self.address, &[reg, value]).await?;
        Ok(())
    }

    /// Read a single register
    async fn read_reg(&mut self, reg: u8) -> Result<u8, Error<E>> {
        let mut buf = [0u8; 1];
        self.i2c.write_read(self.address, &[reg], &mut buf).await?;
        Ok(buf[0])
    }
}
