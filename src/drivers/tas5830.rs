//! TAS5830 Class-D amplifier driver
//!
//! Texas Instruments TAS5830 digital input Class-D amplifier
//! with integrated DSP. Controlled via I2C.
//!
//! Init sequence ported from TI's PPC3-generated tas5805m_config.h.
//! The init is split into two phases matching the reference C code:
//!   1. `init()` — PDN high, reset into Hi-Z (before I2S clocks)
//!   2. `play()` — DSP coefficients + enter Play (after I2S clocks running)

use embassy_rp::gpio::{Level, Output};
use embedded_hal_async::i2c::I2c;
use micromath::F32Ext;

/// TAS5830 I2C address (configured by ADDR pin)
pub const DEFAULT_ADDRESS: u8 = 0x60;

/// Key register addresses (Page 0, Book 0)
#[allow(dead_code)]
pub mod reg {
    pub const PAGE_SELECT: u8 = 0x00;
    pub const DEVICE_CTRL: u8 = 0x03; // Device state: 0=DeepSleep, 1=Sleep, 2=Hi-Z, 3=Play
    pub const DIG_VOL: u8 = 0x4C;
    pub const AGAIN: u8 = 0x54;
    pub const DIE_ID: u8 = 0x67;
    pub const POWER_STATE: u8 = 0x68;
    pub const FAULT: u8 = 0x70;
    pub const CLEAR_FAULT: u8 = 0x78;
    pub const BOOK_SELECT: u8 = 0x7F;
}

